// the designs for the chosen place, with their prices there
const tatChoices=()=>{const[,part]=TAT_PLACES[TAT.p];return TAT_FOR[part].map(id=>{const t=TATTOOS.find(x=>x[0]==id);return[t[0],t[1],t[2]+TAT_EXTRA[part],t[3]]})};
function openTattoo(){const j=NPCS.find(n=>n.name=='Jonna');if(!j||j.m!='tattoo'){say('Jonna only tattoos in her shop, by day.',4000);return}TAT.note='';startPlay('tattoo')}
function buyTattoo(){const[id,name,price]=tatChoices()[TAT.d],[place]=TAT_PLACES[TAT.p];
  if(ME.tattoos.some(t=>t.place==place)){TAT.note=`You already have a tattoo on your ${place.toLowerCase()}. Pick somewhere else.`;return}
  if(ME.cash<price){TAT.note=`The ${name.toLowerCase()} is ${money(price)} there, and you don't have enough money of your own.`;return}
  ME.cash-=price;ME.tattoos.push({id,place,day:DAY});TAT.note=`Jonna gets to work. ${place=='Back'||place=='Chest'?'A long afternoon':'An hour'} later you have ${aan(name.toLowerCase())} on your ${place.toLowerCase()}. "Keep it out of the sea for a week," she says.`;
  if(typeof questEvent=='function')questEvent('tattoo')}
// the design on a patch of skin
function drawTattoo(c,art){const g=c.getContext('2d'),W=c.width;g.fillStyle='#e8b896';g.fillRect(0,0,W,W);
  const gr=g.createRadialGradient(W/2,W/2,W*.15,W/2,W/2,W*.7);gr.addColorStop(0,'rgba(255,230,210,.45)');gr.addColorStop(1,'rgba(120,70,40,.25)');g.fillStyle=gr;g.fillRect(0,0,W,W);
  const rows=art.trim().split('\n'),s=Math.floor(W*.75/12),o=(W-s*12)/2;
  rows.forEach((row,y)=>[...row].forEach((ch,x)=>{if(TAT_INK[ch]){g.globalAlpha=.88;g.fillStyle=TAT_INK[ch];g.fillRect(o+x*s,o+y*s,s,s)}}));g.globalAlpha=1}
